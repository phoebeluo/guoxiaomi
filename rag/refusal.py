"""能力边界拒答：规则化清单（不用相似度分数）。

为什么不用分数
--------------
`tools/calibrate_refusal.py` 实测过：45 篇档下，库内题最高余弦 0.479–0.992，
库外题 0.654–0.898 —— **完全交叠**。要让漏拒率降到 50%，就得误拒 8.3% 的能答问题；
要让漏拒率归零，误拒率会到 52%。不存在可用阈值。

根因：库外题不是「无关话题」，而是「相关话题、库里没写」。
「投诉怎么分级」和语料共享大量词汇，余弦自然高。**相似度衡量的是字面接近，不是有没有答案。**

所以改成规则：只拦「系统原理上不可能做到的事」。这类判断靠业务定义，一句话就能说清，
不需要统计。代价是覆盖不全（只拦得住模式明确的那几类），换来的是**不会误伤能答的问题**。

设计原则：宁可漏拒，不可误拒
--------------------------
误拒的代价 = 用户问了能答的问题，被系统推开（体验直接崩）
漏拒的代价 = 模型拿空资料去答，靠 prompt 的「不知道就明说」兜底（已有实测 0 条模型失败）
两者不对称，所以规则写得很窄，只收**动作明确 + 对象明确**的组合。

不做什么
--------
不把「绝对化承诺」做进这里（「能保证一个都不坏吗」）—— 那不是拒答场景，
是话术约束，prompt 的「禁用绝对化用语」已经在管。
"""

import re

# 每条：(规则名, 正则, 指路话术)
# 正则里用 (?:) 非捕获组，避免 group 编号混乱；中文不加 \b（不适用词边界）
_RULES = [
    (
        # 2026-11-02（W9）收窄：原来「订单/物流」一起拦，但订单状态现在**有工具能查**，
        # 提前拦掉会让工具永远调不到。所以只留「物流轨迹」这一类——
        # 那是真的没有承运商接口，编一句「已到达转运中心」就是纯编造。
        # 「我的订单到哪了」改为放行给模型：它会反问订单号，再调 query_order_status。
        "查物流轨迹",
        re.compile(
            r"(?:物流|快递|包裹|运单).{0,8}"
            r"(?:到哪|在哪|到哪儿|没更新|不动了|几天没|卡住|跟踪|签收没|走到哪)"
            r"|(?:帮我|你帮|能不能帮).{0,6}(?:查|看|跟踪).{0,4}(?:物流|快递|包裹|运单)"
        ),
        "果小蜜这边看不到物流轨迹哦～您可以进入「我的 → 订单详情」看实时物流，"
        "或者点「我的 → 联系客服」，在线客服每天 9:00 至 21:00 在线，能帮您查得更准。",
    ),
    (
        "代改订单",
        re.compile(
            r"(?:帮我|你帮|能不能帮|给我).{0,4}(?:改|修改|取消|催|加急|备注).{0,6}"
            r"(?:订单|地址|电话|收货人|发货|快递|物流)"
        ),
        "修改订单、地址这些操作果小蜜代您做不了哦～您可以在「我的 → 订单详情」里自助修改，"
        "或者联系在线客服（每天 9:00–21:00）帮您处理。",
    ),
    (
        "登记回访",
        re.compile(
            r"(?:帮我|你帮|给我|替我).{0,4}(?:登记|记录|备注|报备|上报|提交).{0,8}"
            r"(?:专人|人工|客服|工单|处理|跟进|回访|联系)"
            r"|(?:让|叫).{0,3}(?:专人|人工|客服|经理).{0,6}(?:联系|回访|处理)"
        ),
        "果小蜜没法代您登记或安排回访哦～如果事情需要人工跟进，"
        "您可以直接在「我的 → 联系客服」留言，客服会按顺序处理并回复您。",
    ),
    (
        "赔付审批",
        # 只收「动作类」：帮我申请/审批/办理。**不收「多久到账」这类时间查询** ——
        # 「退款一般多久到账」库里《售后-退款到账时间》写得很清楚，是知识问题不是能力问题。
        # 第一版把时间查询也收进来，实测误拒了 #33，已删。
        re.compile(
            r"(?:帮我|你帮|给我|替我).{0,4}(?:申请|审批|批准|办理|走).{0,4}"
            r"(?:赔付|理赔|退款|补偿|优惠券)"
        ),
        "赔付和退款需要客服核验凭证后处理，果小蜜无法代您提交哦～"
        "您把整体照、细节照和订单号发到「我的 → 联系客服」，客服会按坏果占比标准核算，"
        "赔付款原路退回；到账时间以支付渠道为准。",
    ),
]

# 内部信息类：库里没有、也不该编的业务规则
_INFO_RULES = [
    (
        "内部流程细节",
        re.compile(r"(?:你们)?(?:内部|公司).{0,6}(?:怎么|如何|谁).{0,6}(?:分级|划分|考核|负责|处理流程)"),
        "这些属于公司内部流程，果小蜜这边没有对外口径，不能凭空说哦～"
        "您如果对处理结果有疑问，可以在「我的 → 联系客服」提出，客服会给您正式答复。",
    ),
]


def check(query):
    """命中则返回 (规则名, 话术)，否则 None。

    顺序：先查内部信息，再查能力类。两者都只做「明确命中」，不做模糊判断。
    """
    q = (query or "").strip()
    if not q:
        return None
    for name, pattern, reply in _INFO_RULES + _RULES:
        if pattern.search(q):
            return name, reply
    return None


def all_rules():
    """给测试与文档用：返回 [(规则名, 正则字符串, 话术)]。"""
    return [(n, p.pattern, r) for n, p, r in _INFO_RULES + _RULES]


if __name__ == "__main__":
    samples = [
        "我的订单物流三天没更新了，你帮我查一下到底到哪了。",
        "我要投诉，你们内部对投诉是怎么分级的？由谁负责处理？",
        "你帮我登记一下，让专人明天联系我处理。",
        "我的退款什么时候到账？",
        "满多少免运费？",
        "坏果怎么赔？",
        "发什么快递？",
        "车厘子怎么保存？",
    ]
    for s in samples:
        hit = check(s)
        print(("✓ " if hit else "· ") + s[:34] + ("  → " + hit[0] if hit else ""))
