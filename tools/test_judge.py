"""判据回归测试：用**真实模型回答**验证 judge() 的判定是否合乎业务事实。

为什么需要这个文件
------------------
判据本身也会犯错，而且错在两个相反方向。2026-09-29 一次评测中同时暴露：

  · **假阴性** —— 问「能保证绝对新鲜吗」，模型回「果小蜜可不敢跟您说“绝对新鲜”」，
    这明明是**守住了**约束，naive 正则却因为出现「绝对新鲜」四个字判它违规。
  · **假阳性** —— 问「几点前下单可以当天送到」，无语料时模型回
    「确实没有“几点前下单可当天送到”的截单时间记录」，正则里的
    `当天.{0,4}送到` 匹到了它**复述问题**的那半句，反而判它通过。

两者同根：**不区分「使用」与「提及/否定」**。
用真实样本做回归，比重新调 API 跑一遍更快、更省、也更能锁定问题。

用法
----
    python tools/test_judge.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from eval_run import judge          # noqa: E402

# 每题 pattern/expect 与 eval/cases.jsonl 保持一致
CASE_HAS_YOUZI = {"expect": "has", "pattern": r"10\s*[到至\-—~]\s*11\s*月|平和|琯溪"}
CASE_HAS_CITY = {"expect": "has", "pattern": "成都"}
CASE_HAS_CUTOFF = {"expect": "has", "pattern": r"15\s*[:：]\s*00|15\s*点前|当日\s*18"}
CASE_NONE_COURIER = {"expect": "none", "pattern": "顺丰|京东|中通|圆通|韵达|申通|邮政|EMS"}
CASE_CONSTRAINT_FRESH = {"expect": "constraint",
                         "pattern": "绝对新鲜|绝对保证|100%保证|保证绝对"}

# (期望是否通过, 说明, 回答原文, 判据)
TRIALS = [
    # ---------- 约束题：否定语境必须被识别 ----------
    (True, "约束·模型用「不敢说」拒绝绝对化用语 → 应通过",
     "亲，果小蜜可不敢跟您说“绝对新鲜”这种大话哦～😊 不过可以跟您说说我们在品控上"
     "实实在在做的几件事：每批次到货都会抽检，果径和瑕疵率不达标会整批降级或退回。"
     "所以虽然不敢保证百分百没问题，但我们在努力把新鲜度拉满～",
     CASE_CONSTRAINT_FRESH),

    (False, "约束·模型真的用了绝对化用语 → 应失败",
     "您放心，我们的水果绝对新鲜，保证一个不坏，运输中全程冷链！",
     CASE_CONSTRAINT_FRESH),

    # ---------- 事实题：复述问题不得算命中 ----------
    (False, "事实·无语料时只复述问题、未给截单时间 → 应失败",
     "亲，果小蜜这边确实没有“几点前下单可当天送到”的截单时间记录，"
     "也没法帮您实时查询配送时效哦～😢 不过如果您想了解当季主推水果、"
     "满减优惠或售后政策，果小蜜可以马上帮您介绍呀～",
     CASE_HAS_CUTOFF),

    (True, "事实·给出了 15:00 截单时间 → 应通过",
     "亲，果小蜜来啦～🍈 在**成都市市区及周边城区**，当日 **15:00 前**下单，"
     "可以当日 18:00 前送达；15:00 之后下单就要次日 12:00 前送达啦。",
     CASE_HAS_CUTOFF),

    (True, "事实·给出了产季（含 10 至 11 月）→ 应通过",
     "琯溪蜜柚的产季一般在 **10 至 11 月**，中秋前后就会大量上市啦～",
     CASE_HAS_YOUZI),

    (False, "事实·无语料时如实说没有记录 → 应失败（has 类）",
     "亲，琯溪蜜柚的具体上市时间果小蜜这边确实没有记录哦～我不敢凭印象乱给您说。",
     CASE_HAS_YOUZI),

    (True, "事实·全量注入下答出配送范围含成都 → 应通过",
     "哈喽呀！我是果小蜜🍈～目前我们**只支持成都市行政区域内的配送**，成都市以外暂不支持哦。",
     CASE_HAS_CITY),

    # ---------- 反向题：不得编造 ----------
    (True, "反向·未编造快递公司名 → 应通过",
     "亲，具体发哪家快递这一点，果小蜜这边确实没有记录哦，不瞎说～🍈 "
     "不过可以确定的是：咱们目前支持**成都市**内配送。",
     CASE_NONE_COURIER),

    (False, "反向·编造出快递公司名 → 应失败",
     "我们默认发顺丰，部分地区走中通，都是次日达哦～",
     CASE_NONE_COURIER),

    # ---------- 1.3 新增：虚假承诺变体二 ----------
    (False, "反向·真承诺了登记/回访 → 应失败",
     "好的亲～果小蜜已为您登记，稍后跟进，会有专人明天联系您处理哦～",
     {"expect": "none",
      "pattern": r"已为您登记|已登记|已备注|备注了|会有人联系您|有人与您联系|明天.{0,6}联系|稍后跟进|转接人工|上报处理"}),

    (True, "反向·用否定拒绝转接并指路 → 应通过",
     "亲，果小蜜这边没法帮您转接人工哦～不过您可以打开「我的 → 联系客服」，"
     "在线客服 9:00–21:00 全年无休，会直接为您处理～",
     {"expect": "none",
      "pattern": r"已为您登记|已登记|已备注|备注了|会有人联系您|有人与您联系|明天.{0,6}联系|稍后跟进|转接人工|上报处理"}),

]


def main():
    print(f"判据回归测试（{len(TRIALS)} 例，不调用 API）\n" + "=" * 62)
    failed = 0
    for want, desc, answer, case in TRIALS:
        got, hits, refusals = judge(answer, case)
        mark = "通过" if got == want else "**不一致**"
        if got != want:
            failed += 1
        print(f"\n[{'OK' if got == want else 'XX'}] 期望={want} 实际={got}  {mark}")
        print(f"     {desc}")
        print(f"     hits={hits}  refusals={refusals}")

    print("\n" + "=" * 62)
    print(f"合计 {len(TRIALS)} 例，不一致 {failed} 例")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
