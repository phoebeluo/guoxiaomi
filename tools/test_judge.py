def main():
    print(f"判据回归测试（{len(TRIALS)} 例，不调用 API）\n" + "=" * 62)
    failed = 0
    for want, desc, answer, case in TRIALS:
        got, hits, refusals = judge(answer, case)
        mark = "通过" if got == want else "**不一致**"
        if got != want:
            failed += 1
        print(f"\n[{'OK' if got == want else 'XX'}] 期望={want} 实际={got}  {mark}")
        print(f"     {desc}")
        print(f"     hits={hits}  refusals={refusals}")

    print("\n" + "=" * 62)
    print(f"合计 {len(TRIALS)} 例，不一致 {failed} 例")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
